// gencall generates typed call wrappers for the gomock package.
// Run via: go run ./internal/gencall/main.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

const (
	maxArgs    = 12
	maxReturns = 5
)

// chainMethod describes a chaining method on FinalizedCallN/CallN_M.
type chainMethod struct {
	name   string
	params string
	args   string
}

// chainMethods lists all ordering/cardinality chain methods.
var chainMethods = []chainMethod{
	{"AnyTimes", "", ""},
	{"MinTimes", "n int", "n"},
	{"MaxTimes", "n int", "n"},
	{"Times", "n int", "n"},
	{"After", "preReq CallHolder", "preReq.getCall()"},
}

func main() {
	var buf bytes.Buffer
	buf.WriteString(
		"// Code generated by internal/gencall/main.go;" +
			" DO NOT EDIT.\n\npackage gomock\n",
	)
	for n := 0; n <= maxArgs; n++ {
		writeFinalizedCall(&buf, n)
	}
	for n := 0; n <= maxArgs; n++ {
		for m := 0; m <= maxReturns; m++ {
			writeCallType(&buf, n, m)
		}
	}
	for n := 0; n <= maxArgs; n++ {
		for m := 0; m <= maxReturns; m++ {
			writeDispatch(&buf, n, m)
		}
	}
	for n := 0; n <= maxArgs; n++ {
		writeFinalizedCallV(&buf, n)
	}
	for n := 0; n <= maxArgs; n++ {
		for m := 0; m <= maxReturns; m++ {
			writeCallTypeV(&buf, n, m)
		}
	}
	for n := 0; n <= maxArgs; n++ {
		for m := 0; m <= maxReturns; m++ {
			writeDispatchV(&buf, n, m)
		}
	}
	for m := 1; m <= maxReturns; m++ {
		writeInvoke(&buf, m)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf(
			"format: %v\n---\n%s", err, buf.Bytes(),
		)
	}
	if err := os.WriteFile("typed_calls.go", src, 0o644); err != nil {
		log.Fatalf("write: %v", err)
	}
}

// finalName returns e.g. "FinalizedCall2".
func finalName(n int) string {
	return fmt.Sprintf("FinalizedCall%d", n)
}

// finalTypeParams returns "[A1, A2 any]" or "" for n=0.
func finalTypeParams(n int) string {
	if n == 0 {
		return ""
	}
	parts := make([]string, n)
	for i := range parts {
		parts[i] = fmt.Sprintf("A%d", i+1)
	}
	return "[" + strings.Join(parts, ", ") + " any]"
}

// finalTypeArgs returns "[A1, A2]" or "" for n=0.
func finalTypeArgs(n int) string {
	if n == 0 {
		return ""
	}
	parts := make([]string, n)
	for i := range parts {
		parts[i] = fmt.Sprintf("A%d", i+1)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// finalSelf returns e.g. "*FinalizedCall2[A1, A2]".
func finalSelf(n int) string {
	return "*" + finalName(n) + finalTypeArgs(n)
}

// callTypeName returns e.g. "Call1_2".
func callTypeName(n, m int) string {
	return fmt.Sprintf("Call%d_%d", n, m)
}

// allTypeParams returns "[A1, R1, R2 any]" or "" for n=m=0.
func allTypeParams(n, m int) string {
	if n == 0 && m == 0 {
		return ""
	}
	parts := make([]string, 0, n+m)
	for i := 1; i <= n; i++ {
		parts = append(parts, fmt.Sprintf("A%d", i))
	}
	for i := 1; i <= m; i++ {
		parts = append(parts, fmt.Sprintf("R%d", i))
	}
	return "[" + strings.Join(parts, ", ") + " any]"
}

// allTypeArgs returns "[A1, R1, R2]" or "" for n=m=0.
func allTypeArgs(n, m int) string {
	if n == 0 && m == 0 {
		return ""
	}
	parts := make([]string, 0, n+m)
	for i := 1; i <= n; i++ {
		parts = append(parts, fmt.Sprintf("A%d", i))
	}
	for i := 1; i <= m; i++ {
		parts = append(parts, fmt.Sprintf("R%d", i))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// callSelf returns e.g. "*Call1_2[A1, R1, R2]".
func callSelf(n, m int) string {
	return "*" + callTypeName(n, m) + allTypeArgs(n, m)
}

// doFuncType returns "func()" or "func(A1, A2)".
func doFuncType(n int) string {
	if n == 0 {
		return "func()"
	}
	parts := make([]string, n)
	for i := range parts {
		parts[i] = fmt.Sprintf("A%d", i+1)
	}
	return "func(" + strings.Join(parts, ", ") + ")"
}

// retSignature returns "", " R1", or " (R1, R2, R3)".
func retSignature(m int) string {
	switch m {
	case 0:
		return ""
	case 1:
		return " R1"
	default:
		parts := make([]string, m)
		for i := range parts {
			parts[i] = fmt.Sprintf("R%d", i+1)
		}
		return " (" + strings.Join(parts, ", ") + ")"
	}
}

// doAndReturnFuncType returns e.g. "func(A1) (R1, R2)".
func doAndReturnFuncType(n, m int) string {
	return doFuncType(n) + retSignature(m)
}

// argParams returns "a1 A1, a2 A2".
func argParams(n int) string {
	parts := make([]string, n)
	for i := range parts {
		parts[i] = fmt.Sprintf("a%d A%d", i+1, i+1)
	}
	return strings.Join(parts, ", ")
}

// argList returns "a1, a2, a3".
func argList(n int) string {
	parts := make([]string, n)
	for i := range parts {
		parts[i] = fmt.Sprintf("a%d", i+1)
	}
	return strings.Join(parts, ", ")
}

// retValList returns "*e.retV1, *e.retV2".
func retValList(m int) string {
	parts := make([]string, m)
	for i := range parts {
		parts[i] = fmt.Sprintf("*e.retV%d", i+1)
	}
	return strings.Join(parts, ", ")
}

// zeroReturnList returns "zero1, zero2".
func zeroReturnList(m int) string {
	parts := make([]string, m)
	for i := range parts {
		parts[i] = fmt.Sprintf("zero%d", i+1)
	}
	return strings.Join(parts, ", ")
}

// fatalfStmt builds the ctrl.T.Fatalf(...) statement for n args.
func fatalfStmt(n int) string {
	fmts := make([]string, n)
	for i := range fmts {
		fmts[i] = "%v"
	}
	format := "Unexpected call to %T.%v(" +
		strings.Join(fmts, ", ") + ") at %s"
	var args strings.Builder
	args.WriteString("receiver, method")
	for i := 1; i <= n; i++ {
		args.WriteString(fmt.Sprintf(", a%d", i))
	}
	args.WriteString(", origin")
	return fmt.Sprintf(
		`ctrl.T.Fatalf("%s", %s)`, format, args.String(),
	)
}

// finalVName returns e.g. "FinalizedCall2V".
