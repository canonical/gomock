// writeChainMethod writes a chain method that delegates to c.call.
func writeChainMethod(
	buf *bytes.Buffer,
	self, name, params, args string,
) {
	fmt.Fprintf(buf,
		"\nfunc (c %s) %s(%s) %s {\n"+
			"\tc.Call.%s(%s)\n"+
			"\treturn c\n"+
			"}\n",
		self, name, params, self, name, args,
	)
}

// writeCallType writes the CallN_M struct, constructor, and methods.
func writeCallType(buf *bytes.Buffer, n, m int) {
	name := callTypeName(n, m)
	tp := allTypeParams(n, m)
	self := callSelf(n, m)
	finName := finalName(n)
	finArgs := finalTypeArgs(n)
	finSelf := finalSelf(n)
	doFunc := doFuncType(n)

	// Struct definition.
	fmt.Fprintf(buf,
		"\n// %s wraps %s for a method with %d args"+
			" and %d return values.\n"+
			"type %s%s struct {\n"+
			"\t%s%s\n",
		name, finName, n, m,
		name, tp,
		finName, finArgs,
	)
	for i := 1; i <= n; i++ {
		fmt.Fprintf(buf, "\tm%d Matcher\n", i)
	}
	if m > 0 {
		for i := 1; i <= m; i++ {
			fmt.Fprintf(buf, "\tretV%d *R%d\n", i, i)
		}
		fmt.Fprintf(buf,
			"\tdoReturnFn %s\n",
			doAndReturnFuncType(n, m),
		)
	}
	buf.WriteString("}\n")

	// Constructor.
	var ctorExtra string
	if n > 0 {
		mps := make([]string, n)
		for i := range mps {
			mps[i] = fmt.Sprintf("m%d Matcher", i+1)
		}
		ctorExtra = ", " + strings.Join(mps, ", ")
	}
	ctorTA := allTypeArgs(n, m)
	// String implements fmt.Stringer.
	var matchersArg string
	if n == 0 {
		matchersArg = "nil"
	} else {
		parts := make([]string, n)
		for i := range parts {
			parts[i] = fmt.Sprintf("c.m%d", i+1)
		}
		matchersArg = "[]Matcher{" + strings.Join(parts, ", ") + "}"
	}
	fmt.Fprintf(buf,
		"\nfunc (c %s) String() string {\n"+
			"\treturn formatCallString(c.receiver, c.method, %s, c.origin)\n"+
			"}\n",
		self, matchersArg,
	)

	fmt.Fprintf(buf,
		"\n// NewCall%d_%d creates a new %s expectation.\n"+
			"func NewCall%d_%d%s("+
			"t TestHelper, receiver any, method string%s"+
			") *%s%s {\n"+
			"\tt.Helper()\n"+
			"\tc := &%s%s{\n"+
			"\t\t%s: %s%s{\n"+
			"\t\t\treceiver: receiver,\n"+
			"\t\t\tmethod:   method,\n"+
			"\t\t\torigin:   callerInfo(2),\n"+
			"\t\t},\n",
		n, m, name,
		n, m, tp, ctorExtra,
		name, ctorTA,
		name, ctorTA,
		finName, finName, finArgs,
	)
	for i := 1; i <= n; i++ {
		fmt.Fprintf(buf, "\t\tm%d: m%d,\n", i, i)
	}
	fmt.Fprintf(buf,
		"\t}\n"+
			"\tc.%s.Call = newCall(t, c)\n"+
			"\treturn c\n"+
			"}\n",
		finName,
	)

	// Do override — returns *CallN_M to preserve the specific type.
	fmt.Fprintf(buf,
		"\nfunc (c %s) Do(f %s) %s {\n"+
			"\tc.doFns = append(c.doFns, f)\n"+
			"\treturn c\n"+
			"}\n",
		self, doFunc, self,
	)

	// Return and DoAndReturn are only present when m > 0.
	if m > 0 {
		retParams := make([]string, m)
		for i := range retParams {
			retParams[i] = fmt.Sprintf("r%d R%d", i+1, i+1)
		}
		fmt.Fprintf(buf,
			"\nfunc (c %s) Return(%s) %s {\n",
			self, strings.Join(retParams, ", "), finSelf,
		)
		for i := 1; i <= m; i++ {
			fmt.Fprintf(buf, "\tc.retV%d = &r%d\n", i, i)
		}
		fmt.Fprintf(buf, "\treturn &c.%s\n}\n", finName)

		drFunc := doAndReturnFuncType(n, m)
		fmt.Fprintf(buf,
			"\nfunc (c %s) DoAndReturn(f %s) %s {\n"+
				"\tc.doReturnFn = f\n"+
				"\treturn &c.%s\n"+
				"}\n",
			self, drFunc, finSelf, finName,
		)
	}

	// Chain method overrides — return *CallN_M.
	for _, cm := range chainMethods {
		writeChainMethod(buf, self, cm.name, cm.params, cm.args)
	}
}

